"""Git repository creation and documentation push (GitHub)"""
import os
import base64
import requests
from typing import Dict, List

class GitConnector:
    def __init__(self, settings=None):
        if settings:
            self.token = settings.github_token or os.getenv("GITHUB_TOKEN", "")
            self.repo_owner = settings.github_username or os.getenv("GITHUB_OWNER", "")
        else:
            self.token = os.getenv("GITHUB_TOKEN", "")
            self.repo_owner = os.getenv("GITHUB_OWNER", "")
    
    def is_configured(self) -> bool:
        return bool(self.token and self.repo_owner)
    
    def create_repository(self, repo_name: str, description: str = "", private: bool = True) -> Dict:
        """Create a GitHub repository"""
        if not self.is_configured():
            return {"error": "GitHub not configured", "skipped": True}
        url = "https://api.github.com/user/repos"
        headers = {"Authorization": f"token {self.token}", "Accept": "application/vnd.github.v3+json"}
        payload = {
            "name": repo_name,
            "description": description,
            "private": private,
            "auto_init": True
        }
        try:
            resp = requests.post(url, json=payload, headers=headers)
            if resp.status_code == 201:
                return resp.json()
            else:
                return {"error": resp.text, "status": resp.status_code}
        except Exception as e:
            return {"error": str(e)}
    
    def create_or_update_file(self, repo_name: str, file_path: str, content: str, commit_message: str) -> Dict:
        """Create or update a file in the repository"""
        if not self.is_configured():
            return {"error": "GitHub not configured"}
        url = f"https://api.github.com/repos/{self.repo_owner}/{repo_name}/contents/{file_path}"
        headers = {"Authorization": f"token {self.token}", "Accept": "application/vnd.github.v3+json"}
        encoded_content = base64.b64encode(content.encode()).decode()
        # Try to get existing file SHA if updating
        existing = requests.get(url, headers=headers)
        sha = existing.json().get('sha') if existing.status_code == 200 else None
        payload = {
            "message": commit_message,
            "content": encoded_content,
            "branch": "main"
        }
        if sha:
            payload["sha"] = sha
        try:
            resp = requests.put(url, json=payload, headers=headers)
            return resp.json() if resp.status_code in (200, 201) else {"error": resp.text}
        except Exception as e:
            return {"error": str(e)}
    
    def push_documentation(self, repo_name: str, docs: Dict[str, str]) -> Dict:
        """Push multiple documentation files to the repo"""
        if not self.is_configured():
            return {"skipped": True, "message": "GitHub credentials missing"}
        # Create repository first
        repo_result = self.create_repository(repo_name, "Auto-generated by DocuForge AI")
        if repo_result.get("error"):
            return repo_result
        
        successful_files = 0
        for doc_type, content in docs.items():
            # content is HTML string; convert to .html
            file_path = f"docs/{doc_type}.html"
            result = self.create_or_update_file(repo_name, file_path, content, f"Add {doc_type} documentation")
            if not result.get("error"):
                successful_files += 1
        return {"files_uploaded": successful_files, "repo_url": f"https://github.com/{self.repo_owner}/{repo_name}"}
